"""Analyze real QRBENCH logs; optional manually measured TRIAL lines. Stdlib only.

Example manual marker (not generated by firmware):
[TRIAL] code=A success=1 latency_ms=742
Latency is physical presentation-to-correct-result, measured separately by video.
"""
import argparse
import json
import math
import re
import statistics
from collections import defaultdict
from pathlib import Path


def percentile(values, quantile):
    """Nearest-rank percentile; returns None for no actual observations."""
    return sorted(values)[max(0, math.ceil(len(values) * quantile) - 1)] if values else None


def summarize(text):
    scans, trials, boots, diagnostics, reset_reasons = [], [], 0, [], []
    segments = defaultdict(list)
    for line in text.splitlines():
        if '[BOOT] Standalone' in line:
            boots += 1
        reset = re.search(r'\[BOOT\] Reset reason=(\d+)', line)
        if reset:
            reset_reasons.append(int(reset.group(1)))
        if '[DIAG]' in line:
            diagnostics.append({key: float(value) for key, value in re.findall(r'(\w+)=(-?[\d.]+)', line)})
        if '[QRBENCH]' not in line and '[TRIAL]' not in line:
            continue
        fields = dict(re.findall(r'(\w+)=([\w.-]+)', line))
        if '[TRIAL]' in line:
            trials.append(fields)
        elif all(key in fields for key in ('session', 'attempt', 'completed_ms', 'total_us', 'decoded', 'ready_us')):
            row = {key: int(value) for key, value in fields.items()}
            scans.append(row)
            segments[(boots, row['session'])].append(row['completed_ms'])
    if not scans:
        raise ValueError('No per-scan QRBENCH records. Enable QR_BENCHMARK_LOG_EACH_SCAN for QR-06; sparse QR-05 QRTIME lines cannot establish full-scan percentiles.')
    successes = [row['ready_us'] / 1000 for row in scans if row['decoded']]
    intervals, duration = 0, 0
    for timestamps in segments.values():
        if len(timestamps) > 1:
            elapsed = (timestamps[-1] - timestamps[0]) & 0xffffffff
            if elapsed:
                intervals += len(timestamps) - 1
                duration += elapsed
    latencies = [float(row['latency_ms']) for row in trials if row.get('success') == '1' and 'latency_ms' in row]
    by_code = {}
    for code in sorted({row.get('code', 'unspecified') for row in trials}):
        rows = [row for row in trials if row.get('code', 'unspecified') == code]
        by_code[code] = {'trials': len(rows), 'successes': sum(row.get('success') == '1' for row in rows)}
    return {
        'records': len(scans),
        'average_processing_ms': statistics.mean(row['total_us'] / 1000 for row in scans),
        'completed_scans_per_second': intervals * 1000 / duration if duration else None,
        'successful_scan_to_result_ms': {
            'definition': 'attempt start to ready result; NOT presentation-to-recognition latency',
            'samples': len(successes), 'median': statistics.median(successes) if successes else None,
            'p95_nearest_rank': percentile(successes, .95)},
        'failed_frame_attempts': sum(not row.get('captured', 1) for row in scans),
        'mean_phase_ms': {key: statistics.mean(row.get(key, 0) / 1000 for row in scans)
                          for key in ('capture_us', 'convert_us', 'gray_us', 'detect_us', 'decode_us')},
        'presentation_trials': {
            'definition': 'manual/video measurements supplied by tester', 'by_code': by_code,
            'success_rate': sum(row.get('success') == '1' for row in trials) / len(trials) if trials else None,
            'median_ms': statistics.median(latencies) if latencies else None,
            'p95_ms_nearest_rank': percentile(latencies, .95)},
        'observed_additional_boots': max(0, boots - 1),
        'reset_reasons_in_log': reset_reasons,
        'diagnostic_ranges': {
            key: {'first': values[0], 'last': values[-1], 'min': min(values), 'max': max(values)}
            for key in ('heap', 'psram', 'rssi', 'capture_fail', 'send_timeouts')
            if (values := [row[key] for row in diagnostics if key in row])},
        'limitations': 'Boots can include intentional resets; inspect logs. Capture failure counter, heap, PSRAM, RSSI and send timeouts remain in DIAG. Repeated decode frames are not independent presentation trials.'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('log', type=Path)
    args = parser.parse_args()
    try:
        print(json.dumps(summarize(args.log.read_text(encoding='utf-8', errors='replace')), indent=2))
    except ValueError as error:
        parser.exit(2, str(error) + '\n')
